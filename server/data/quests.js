function metadata(quest) {
  const { steps, ...meta } = quest;
  return { ...meta, steps: steps.length, reward: steps.length * 20 + 40 };
}
function publicStep(step) {
  const { answer, explanation, ...safe } = step;
  return safe;
}
function matches(step, answer) {
  if (step.type === "number")
    return (
      typeof answer === "string" &&
      /^-?\d{1,10}([.,]\d{1,6})?$/.test(answer.trim()) &&
      Number(answer.trim().replace(",", ".")) === step.answer
    );
  if (step.type === "order")
    return (
      Array.isArray(answer) &&
      answer.length === step.answer.length &&
      answer.every((value, index) => value === step.answer[index])
    );
  return Number.isInteger(answer) && answer === step.answer;
}
module.exports = { quests, metadata, publicStep, matches };
